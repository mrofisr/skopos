package chclient

import (
	"context"
	"regexp"
	"strings"
	"sync"
)

// QueryRecord is one statement observed for a request.
type QueryRecord struct {
	SQL      string
	Tables   []string
	ReadRows uint64
	Error    string
}

// Recorder collects the statements issued for one logical request. It is safe
// for concurrent use, but callers normally create one per request.
type Recorder struct {
	mu      sync.Mutex
	records []QueryRecord
}

// Record appends one statement.
func (r *Recorder) Record(record QueryRecord) {
	if r == nil {
		return
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	r.records = append(r.records, record)
}

// Statements returns a copy of the recorded statements.
func (r *Recorder) Statements() []QueryRecord {
	if r == nil {
		return nil
	}
	r.mu.Lock()
	defer r.mu.Unlock()
	out := make([]QueryRecord, len(r.records))
	copy(out, r.records)
	return out
}

type recorderContextKey struct{}

// WithRecorder attaches a recorder to ctx.
func WithRecorder(ctx context.Context, recorder *Recorder) context.Context {
	return context.WithValue(ctx, recorderContextKey{}, recorder)
}

// RecorderFromContext returns the request recorder, or nil.
func RecorderFromContext(ctx context.Context) *Recorder {
	recorder, _ := ctx.Value(recorderContextKey{}).(*Recorder)
	return recorder
}

var tablePattern = regexp.MustCompile(`(?i)\b(?:from|join)\s+([A-Za-z0-9_.` + "`" + `]+)`)

// tablesFromSQL returns the table names after FROM and JOIN. It is a test
// helper, not a SQL parser: every query in this repository is generated by
// sqlgen and uses simple identifiers or backticked names.
func tablesFromSQL(sql string) []string {
	matches := tablePattern.FindAllStringSubmatch(sql, -1)
	seen := make(map[string]bool, len(matches))
	tables := make([]string, 0, len(matches))
	for _, match := range matches {
		name := strings.ReplaceAll(match[1], "`", "")
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		tables = append(tables, name)
	}
	return tables
}
