// Package workflowsdoc generates docs/workflows.md from the workflow files and
// the checked-in ruleset. The document is checked in and CI fails on a diff.
package workflowsdoc

import (
	"context"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/mrofisr/skopos/tools/repoctl/internal/command"
	"github.com/mrofisr/skopos/tools/repoctl/internal/ruleset"
	"github.com/mrofisr/skopos/tools/repoctl/internal/workflowlint"
)

// Command implements `repoctl workflows-doc`.
type Command struct{}

// Name implements command.Command.
func (Command) Name() string { return "workflows-doc" }

// Summary implements command.Command.
func (Command) Summary() string { return "generate or check docs/workflows.md" }

// Run implements command.Command.
func (Command) Run(_ context.Context, env command.Env, args []string) error {
	fs := flag.NewFlagSet("workflows-doc", flag.ContinueOnError)
	fs.SetOutput(env.Stderr)
	dir := fs.String("dir", ".github/workflows", "workflow directory")
	rulesetPath := fs.String("ruleset", "docs/security/ruleset.json", "ruleset document")
	out := fs.String("out", "docs/workflows.md", "generated document")
	check := fs.Bool("check", false, "fail when the checked-in document is stale")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() != 0 {
		return fmt.Errorf("unexpected arguments: %v", fs.Args())
	}

	content, err := Generate(*dir, *rulesetPath)
	if err != nil {
		return err
	}
	if *check {
		current, err := os.ReadFile(*out)
		if err != nil {
			return fmt.Errorf("read %s: %w", *out, err)
		}
		if string(current) != string(content) {
			return fmt.Errorf("%s is stale; run go run ./tools/repoctl workflows-doc", *out)
		}
		fmt.Fprintf(env.Stdout, "workflows-doc: %s is current\n", *out)
		return nil
	}
	if err := os.WriteFile(*out, content, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", *out, err)
	}
	fmt.Fprintf(env.Stdout, "workflows-doc: wrote %s\n", *out)
	return nil
}

type workflowInfo struct {
	File     string
	Report   workflowlint.Report
	Required []string
}

// Generate renders the workflow matrix and required-check table.
func Generate(dir, rulesetPath string) ([]byte, error) {
	config, err := ruleset.Load(rulesetPath)
	if err != nil {
		return nil, err
	}
	required := make(map[string]bool, len(config.RequiredChecks()))
	for _, check := range config.RequiredChecks() {
		required[check] = true
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read workflows: %w", err)
	}
	names := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if strings.HasSuffix(name, ".yml") || strings.HasSuffix(name, ".yaml") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	if len(names) == 0 {
		return nil, fmt.Errorf("no workflows under %s", dir)
	}

	workflows := make([]workflowInfo, 0, len(names))
	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, fmt.Errorf("read workflow %q: %w", name, err)
		}
		report, err := workflowlint.Analyze(data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		info := workflowInfo{File: name, Report: report}
		for _, job := range report.Jobs {
			if required[jobTitle(report, job)] {
				info.Required = append(info.Required, jobTitle(report, job))
			}
		}
		workflows = append(workflows, info)
	}

	var builder strings.Builder
	builder.WriteString("# Workflows\n\n")
	builder.WriteString("Generated by `go run ./tools/repoctl workflows-doc`; do not edit by hand.\n")
	builder.WriteString("The source of truth is `.github/workflows/` and `docs/security/ruleset.json`.\n\n")
	builder.WriteString("## Workflow matrix\n\n")
	builder.WriteString("| Workflow | Triggers | Jobs | Required |\n")
	builder.WriteString("| --- | --- | --- | --- |\n")
	for _, workflow := range workflows {
		jobs := make([]string, 0, len(workflow.Report.Jobs))
		for _, job := range workflow.Report.Jobs {
			jobs = append(jobs, backtick(jobTitle(workflow.Report, job)))
		}
		requiredNames := make([]string, 0, len(workflow.Required))
		for _, check := range workflow.Required {
			requiredNames = append(requiredNames, backtick(check))
		}
		fmt.Fprintf(&builder, "| `%s` | %s | %s | %s |\n",
			workflow.File,
			backtickList(workflow.Report.Triggers),
			strings.Join(jobs, ", "),
			emptyDash(requiredNames),
		)
	}

	builder.WriteString("\n## Required checks\n\n")
	builder.WriteString("| Check | Workflow | Job |\n")
	builder.WriteString("| --- | --- | --- |\n")
	for _, check := range config.RequiredChecks() {
		workflow, job := locateCheck(workflows, check)
		if workflow == "" {
			fmt.Fprintf(&builder, "| `%s` | missing | missing |\n", check)
			continue
		}
		fmt.Fprintf(&builder, "| `%s` | `%s` | `%s` |\n", check, workflow, job)
	}
	return []byte(builder.String()), nil
}

func jobTitle(report workflowlint.Report, job string) string {
	if title := report.JobTitles[job]; title != "" {
		return title
	}
	return job
}

func locateCheck(workflows []workflowInfo, check string) (string, string) {
	for _, workflow := range workflows {
		for _, job := range workflow.Report.Jobs {
			if jobTitle(workflow.Report, job) == check {
				return workflow.File, job
			}
		}
	}
	return "", ""
}

func backtick(value string) string { return "`" + value + "`" }

func backtickList(values []string) string {
	if len(values) == 0 {
		return "—"
	}
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, backtick(value))
	}
	return strings.Join(quoted, ", ")
}

func emptyDash(values []string) string {
	if len(values) == 0 {
		return "—"
	}
	return strings.Join(values, ", ")
}
