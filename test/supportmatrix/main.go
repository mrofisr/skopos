// Command supportmatrix generates docs/support-matrix.md from the PromQL,
// LogQL, and TraceQL inventories and the gateway config defaults. CI fails when
// the checked-in document is stale.
package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"math"
	"os"
	"sort"
	"strings"

	"github.com/mrofisr/skopos/internal/config"
	"github.com/mrofisr/skopos/internal/loki"
	"github.com/mrofisr/skopos/internal/prom"
	"github.com/mrofisr/skopos/internal/tempo"
)

type row struct {
	Group     string
	Construct string
	Status    string
	Test      string
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("supportmatrix", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("out", "docs/support-matrix.md", "generated document")
	check := fs.Bool("check", false, "fail when the checked-in document is stale")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() != 0 {
		fmt.Fprintf(stderr, "supportmatrix: unexpected arguments: %v\n", fs.Args())
		return 2
	}
	content, err := Generate()
	if err != nil {
		fmt.Fprintln(stderr, "supportmatrix:", err)
		return 1
	}
	if *check {
		current, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(stderr, "supportmatrix: read %s: %v\n", *out, err)
			return 1
		}
		block, err := extractBlock(string(current))
		if err != nil {
			fmt.Fprintf(stderr, "supportmatrix: %s: %v\n", *out, err)
			return 1
		}
		if block != string(content) {
			fmt.Fprintf(stderr, "supportmatrix: %s is stale; run go run ./test/supportmatrix\n", *out)
			return 1
		}
		fmt.Fprintf(stdout, "supportmatrix: %s is current\n", *out)
		return 0
	}
	current, readErr := os.ReadFile(*out)
	document := string(current)
	if readErr != nil {
		if !errors.Is(readErr, os.ErrNotExist) {
			fmt.Fprintf(stderr, "supportmatrix: read %s: %v\n", *out, readErr)
			return 1
		}
		document = "# Support matrix\n\n"
	}
	updated, err := replaceBlock(document, string(content))
	if err != nil {
		fmt.Fprintf(stderr, "supportmatrix: %v\n", err)
		return 1
	}
	if err := os.WriteFile(*out, []byte(updated), 0o644); err != nil {
		fmt.Fprintf(stderr, "supportmatrix: write %s: %v\n", *out, err)
		return 1
	}
	fmt.Fprintf(stdout, "supportmatrix: wrote %s\n", *out)
	return 0
}

// Generate renders the matrix and limits tables.
func Generate() ([]byte, error) {
	rows, err := buildRows()
	if err != nil {
		return nil, err
	}
	cfg, err := config.FromLookup(func(string) (string, bool) { return "", false })
	if err != nil {
		return nil, fmt.Errorf("load config defaults: %w", err)
	}

	var builder strings.Builder
	builder.WriteString("<!-- BEGIN GENERATED SUPPORT MATRIX -->\n")
	builder.WriteString("Generated by `go run ./test/supportmatrix`; do not edit by hand.\n")
	builder.WriteString("Every row is backed by an executable inventory test.\n\n")

	for _, group := range []string{"PromQL functions", "LogQL constructs", "TraceQL forms"} {
		builder.WriteString("## " + group + "\n\n")
		switch group {
		case "PromQL functions":
			builder.WriteString("| Function | Status | Test |\n| --- | --- | --- |\n")
		case "LogQL constructs":
			builder.WriteString("| Construct | Status | Test |\n| --- | --- | --- |\n")
		default:
			builder.WriteString("| Form | Status | Test |\n| --- | --- | --- |\n")
		}
		for _, entry := range rows {
			if entry.Group != group {
				continue
			}
			fmt.Fprintf(&builder, "| %s | %s | %s |\n",
				escape(entry.Construct), escape(entry.Status), escape(entry.Test))
		}
		builder.WriteString("\n")
	}

	builder.WriteString("## Limits\n\n")
	builder.WriteString("| Limit | Default | Source |\n| --- | --- | --- |\n")
	builder.WriteString("| Maximum query range | " + cfg.MaxQueryRange.String() + " | `internal/config` |\n")
	builder.WriteString(fmt.Sprintf("| Maximum scan rows | %d | `internal/config` |\n", cfg.MaxScanRows))
	builder.WriteString(fmt.Sprintf("| Maximum rows to read | %d | `internal/config` |\n", cfg.MaxRowsToRead))
	builder.WriteString(fmt.Sprintf("| Maximum result rows | %d | `internal/config` |\n", cfg.MaxResultRows))
	builder.WriteString("| Maximum response bytes | " + formatBytes(cfg.MaxResponseBytes) + " | `internal/config` |\n")
	builder.WriteString("| Maximum request bytes | " + formatBytes(cfg.MaxRequestBytes) + " | `internal/config` |\n")
	builder.WriteString("| Query timeout | " + cfg.QueryTimeout.String() + " | `internal/config` |\n")
	builder.WriteString("| Maximum execution time | " + cfg.MaxExecutionTime.String() + " | `internal/config` |\n")
	builder.WriteString("| Maximum memory usage | " + formatBytesUint(cfg.MaxMemoryUsage) + " | `internal/config` |\n")
	builder.WriteString("| In-flight cap | unset | admission limiter; wired by AX-23 |\n")
	builder.WriteString(fmt.Sprintf("| Range points per slot | %d | `internal/config` |\n", cfg.PointsPerSlot))
	builder.WriteString(fmt.Sprintf("| Instant rows per slot | %d | `internal/config` |\n", cfg.RowsPerSlot))
	builder.WriteString(fmt.Sprintf("| Instant fallback weight | %d | `internal/config` |\n", cfg.InstantFallbackWeight))
	builder.WriteString(fmt.Sprintf("| Work weighting enabled | %t | `internal/config` |\n", !cfg.DisableWorkWeighting))
	builder.WriteString("<!-- END GENERATED SUPPORT MATRIX -->\n")
	return []byte(builder.String()), nil
}

const (
	beginMarker = "<!-- BEGIN GENERATED SUPPORT MATRIX -->"
	endMarker   = "<!-- END GENERATED SUPPORT MATRIX -->"
)

// replaceBlock swaps the generated block in an existing document. When the
// document or its markers are missing, the block is appended so a new checkout
// can bootstrap the file.
func replaceBlock(document, block string) (string, error) {
	begin := strings.Index(document, beginMarker)
	end := strings.Index(document, endMarker)
	if begin < 0 && end < 0 {
		return document + "\n" + block, nil
	}
	if begin < 0 || end < 0 || end < begin {
		return "", errors.New("support matrix markers are malformed")
	}
	return document[:begin] + block + document[end+len(endMarker)+1:], nil
}

// extractBlock returns the generated block from a document.
func extractBlock(document string) (string, error) {
	begin := strings.Index(document, beginMarker)
	end := strings.Index(document, endMarker)
	if begin < 0 || end < 0 || end < begin {
		return "", errors.New("generated support-matrix block is missing")
	}
	return document[begin : end+len(endMarker)+1], nil
}

func buildRows() ([]row, error) {
	rows := make([]row, 0, 200)
	for _, function := range prom.FunctionInventory() {
		test := "TestSupportedFunctionsEvaluate"
		if function.Class == prom.FunctionExplicitError {
			test = "TestExplicitErrorFunctionsReturnPrometheusError"
		}
		if function.Class == prom.FunctionParserDisabled {
			test = "TestParserDisabledFunctionsReturnPrometheusError"
		}
		rows = append(rows, row{
			Group:     "PromQL functions",
			Construct: function.Name,
			Status:    string(function.Class),
			Test:      test,
		})
	}
	for _, construct := range loki.Inventory() {
		rows = append(rows, row{
			Group:     "LogQL constructs",
			Construct: construct.Name,
			Status:    string(construct.Class),
			Test:      "TestEveryLogQLConstructClassified",
		})
	}
	rows = append(rows, row{
		Group:     "TraceQL forms",
		Construct: "supported subset: " + tempo.TraceQLSupportedSubset(),
		Status:    "supported",
		Test:      "TestRejectedFormsMatchDocs",
	})
	for _, form := range tempo.TraceQLRejectedForms() {
		rows = append(rows, row{
			Group:     "TraceQL forms",
			Construct: form.Query + " -> " + form.Want,
			Status:    "explicit error",
			Test:      "TestRejectedFormsMatchDocs",
		})
	}
	if err := validateRows(rows); err != nil {
		return nil, err
	}
	sort.SliceStable(rows, func(i, j int) bool {
		if rows[i].Group != rows[j].Group {
			return rows[i].Group < rows[j].Group
		}
		return rows[i].Construct < rows[j].Construct
	})
	return rows, nil
}

func validateRows(rows []row) error {
	if len(rows) == 0 {
		return errors.New("support matrix has no rows")
	}
	seen := make(map[string]bool, len(rows))
	for _, entry := range rows {
		if entry.Group == "" || entry.Construct == "" || entry.Status == "" {
			return fmt.Errorf("support matrix row is incomplete: %#v", entry)
		}
		if entry.Test == "" {
			return fmt.Errorf("support matrix row %q has no test reference", entry.Construct)
		}
		key := entry.Group + "\x00" + entry.Construct
		if seen[key] {
			return fmt.Errorf("support matrix row %q appears twice in %s", entry.Construct, entry.Group)
		}
		seen[key] = true
	}
	return nil
}

func escape(value string) string {
	value = strings.ReplaceAll(value, "|", `\|`)
	return strings.ReplaceAll(value, "\n", " ")
}

func formatBytesUint(value uint64) string {
	if value > math.MaxInt64 {
		return fmt.Sprintf("%d bytes", value)
	}
	return formatBytes(int64(value))
}

func formatBytes(value int64) string {
	if value <= 0 {
		return fmt.Sprintf("%d", value)
	}
	units := []string{"B", "KiB", "MiB", "GiB", "TiB"}
	size := float64(value)
	unit := 0
	for size >= 1024 && unit < len(units)-1 {
		size /= 1024
		unit++
	}
	if unit == 0 {
		return fmt.Sprintf("%d B", value)
	}
	return fmt.Sprintf("%d (%.0f %s)", value, size, units[unit])
}
